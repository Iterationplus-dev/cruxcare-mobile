import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

/**
 * `android/` is generated and git-ignored (see .gitignore), so hand edits to
 * the native project do not survive a fresh clone or a `cap add android`.
 * Everything the Android app needs beyond what Capacitor generates is applied
 * here instead, the same way scripts/patch-native-biometric-gradle.mjs handles
 * plugin Gradle files.
 *
 * Every edit is idempotent — the script is safe to run on every install.
 */

const ANDROID = resolve('android');

if (!existsSync(ANDROID)) {
  // Web-only checkout, or `cap add android` has not been run yet.
  process.exit(0);
}

const changes = [];

function edit(path, transform) {
  const file = resolve(path);
  if (!existsSync(file)) return;

  const source = readFileSync(file, 'utf8');
  const patched = transform(source);
  if (patched && patched !== source) {
    writeFileSync(file, patched);
    changes.push(path);
  }
}

function write(path, contents) {
  const file = resolve(path);
  if (existsSync(file)) return;

  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, contents);
  changes.push(path);
}

// ---------------------------------------------------------------------------
// 1. Notification status-bar icon
// ---------------------------------------------------------------------------
// Android renders the notification icon as a mask: anything but a white,
// transparent-background silhouette shows up as a grey square on API 21+.
write(
  'android/app/src/main/res/drawable/ic_stat_cruxcare.xml',
  `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/patch-android-push-and-monnify.mjs -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">
    <path
        android:fillColor="#FFFFFFFF"
        android:pathData="M6.05,8.05c-2.73,2.73-2.73,7.15-0.02,9.88c1.47-3.4,4.09-6.24,7.36-7.93c-2.77,2.34-4.71,5.61-5.39,9.32c2.6,1.23,5.8,0.78,7.95-1.37C19.43,14.5,20,4,20,4S9.5,4.57,6.05,8.05z" />
</vector>
`,
);

// ---------------------------------------------------------------------------
// 2. Notification accent colour
// ---------------------------------------------------------------------------
edit('android/app/src/main/res/values/colors.xml', (source) => {
  if (source.includes('notificationAccent')) return source;
  // Matches --cc-color-primary in src/theme/tokens.css.
  return source.replace(
    '</resources>',
    '    <color name="notificationAccent">#0E7C6B</color>\n</resources>',
  );
});

// ---------------------------------------------------------------------------
// 3. AndroidManifest: POST_NOTIFICATIONS, FCM defaults, Monnify theme conflict
// ---------------------------------------------------------------------------
edit('android/app/src/main/AndroidManifest.xml', (source) => {
  let next = source;

  // The `tools` namespace is needed by the theme override below.
  if (!next.includes('xmlns:tools=')) {
    next = next.replace(
      '<manifest xmlns:android="http://schemas.android.com/apk/res/android">',
      '<manifest xmlns:android="http://schemas.android.com/apk/res/android"\n    xmlns:tools="http://schemas.android.com/tools">',
    );
  }

  // Monnify's AAR declares android:theme on <application>. Two different
  // values on the same attribute is a manifest-merger failure, and the app's
  // own theme is the one that must win.
  if (!next.includes('tools:replace="android:theme"')) {
    next = next.replace(
      '        android:theme="@style/AppTheme">',
      '        android:theme="@style/AppTheme"\n        tools:replace="android:theme">',
    );
  }

  // Android 13+ (this app targets 36) delivers nothing without a granted
  // POST_NOTIFICATIONS runtime permission, and the Capacitor push plugin's
  // own manifest does not declare it.
  if (!next.includes('android.permission.POST_NOTIFICATIONS')) {
    next = next.replace(
      '    <uses-permission android:name="android.permission.INTERNET" />',
      '    <uses-permission android:name="android.permission.INTERNET" />\n' +
        '    <!-- Required for push notifications on Android 13 (API 33) and newer. -->\n' +
        '    <uses-permission android:name="android.permission.POST_NOTIFICATIONS" />',
    );
  }

  // Without these, Firebase falls back to the app launcher icon (rendered as a
  // grey square) and files every message under a "Miscellaneous" channel the
  // user cannot tune. The channel id must match DEFAULT_CHANNEL_ID in
  // src/services/push/pushNotifications.ts and the backend's payload.
  if (!next.includes('com.google.firebase.messaging.default_notification_channel_id')) {
    next = next.replace(
      '        <provider',
      `        <meta-data
            android:name="com.google.firebase.messaging.default_notification_icon"
            android:resource="@drawable/ic_stat_cruxcare" />
        <meta-data
            android:name="com.google.firebase.messaging.default_notification_color"
            android:resource="@color/notificationAccent" />
        <meta-data
            android:name="com.google.firebase.messaging.default_notification_channel_id"
            android:value="cruxcare-default" />

        <provider`,
    );
  }

  return next;
});

// ---------------------------------------------------------------------------
// 4. JitPack repository for Monnify's transitive dependencies
// ---------------------------------------------------------------------------
// Two of the Monnify SDK's transitive dependencies (MasayukiSuda:BubbleLayout,
// NaikSoftware:StompProtocolAndroid) are published only on JitPack. The plugin
// module declares it too; this covers resolution from the root project.
edit('android/build.gradle', (source) => {
  if (source.includes('jitpack.io')) return source;
  return source.replace(
    'allprojects {\n    repositories {\n        google()\n        mavenCentral()\n    }\n}',
    'allprojects {\n    repositories {\n        google()\n        mavenCentral()\n        // Required by transitive dependencies of the Monnify Android SDK.\n        maven { url = uri("https://jitpack.io") }\n    }\n}',
  );
});

if (changes.length) {
  console.log(`Patched the Android project for push + Monnify:\n  ${changes.join('\n  ')}`);
}

// ---------------------------------------------------------------------------
// 5. Loud warning when FCM cannot possibly work
// ---------------------------------------------------------------------------
if (!existsSync(resolve('android/app/google-services.json'))) {
  console.warn(
    '\n  WARNING  android/app/google-services.json is missing.\n' +
      '           Android push registration will fail at runtime with a\n' +
      '           registrationError, and the google-services Gradle plugin is\n' +
      '           skipped. Download it from the Firebase console for the\n' +
      '           com.cruxcintl.mobile app - see docs/PUSH_NOTIFICATIONS_CONTRACT.md.\n',
  );
}
